"""Describe the selected dusk PNGs with Godot atlases; never modify image pixels.

Only writes resources/art/forest_dusk and source metadata in assets/art/forest_dusk.
Saved scenes are never regenerated by this tool.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/art/forest_dusk'
OUT = ROOT / 'resources/art/forest_dusk'
OUT.mkdir(parents=True, exist_ok=True)


def save(name, text):
    (OUT / name).write_text(text.strip() + '\n', encoding='utf-8')


def rect(values):
    return 'Rect2(%s)' % ', '.join(str(v) for v in values)


def bounds(image, box):
    alpha = image.getchannel('A').crop(box)
    found = alpha.point(lambda value: 255 if value > 150 else 0).getbbox()
    if found is None:
        raise ValueError(f'Empty sprite at {box}')
    left, top, right, bottom = found
    if left < 2 or top < 2 or right > box[2] - box[0] - 2 or bottom > box[3] - box[1] - 2:
        raise ValueError(f'Sprite crosses its cell boundary: {box}, {found}')
    return [box[0] + left - 2, box[1] + top - 2, right - left + 4, bottom - top + 4]


layout = {}
props = Image.open(ART / 'props.png')
for name, box in {
    'hut': (0, 0, 580, 660),
    'pine': (580, 0, 991, 660),
    'logs': (991, 0, 1536, 660),
    'fence': (0, 660, 580, 1024),
    'chest': (580, 660, 991, 1024),
    'rocks': (991, 660, 1536, 1024),
}.items():
    region = bounds(props, box)
    layout[name] = region
    save(name + '.tres', f'''[gd_resource type="AtlasTexture" load_steps=2 format=3]

[ext_resource type="Texture2D" path="res://assets/art/forest_dusk/props.png" id="1"]

[resource]
atlas = ExtResource("1")
region = {rect(region)}
filter_clip = true
''')

for actor in ('scout', 'guard'):
    image = Image.open(ART / (actor + '.png'))
    row_edges = [0, 335, 665, 1024]
    column_edges = [0, 430, 770, 1100, 1536]
    regions = [bounds(image, (column_edges[c], row_edges[r], column_edges[c + 1], row_edges[r + 1]))
               for r in range(3) for c in range(4)]
    width = max(region[2] for region in regions)
    height = max(region[3] for region in regions)
    layout[actor] = {'regions': regions, 'canvas': [width, height], 'display_scale': 64.0 / height}
    text = f'''[gd_resource type="SpriteFrames" load_steps=14 format=3]

[ext_resource type="Texture2D" path="res://assets/art/forest_dusk/{actor}.png" id="1"]
'''
    for index, region in enumerate(regions):
        w, h = region[2:]
        text += f'''
[sub_resource type="AtlasTexture" id="Frame_{index}"]
atlas = ExtResource("1")
region = {rect(region)}
margin = {rect([(width-w)/2, height-h, width-w, height-h])}
filter_clip = true
'''
    text += '\n[resource]\nanimations = [\n'
    for row, animation in enumerate(('down', 'side', 'up')):
        frames = ', '.join('{"duration": 1.0, "texture": SubResource("Frame_%d")}' % (row*4+c) for c in range(4))
        text += '{"frames": [%s], "loop": true, "name": &"%s", "speed": 8.0},\n' % (frames, animation)
    save(actor + '_frames.tres', text + ']\n')

(ART / 'SOURCES.json').write_text(json.dumps({
    'generator': 'Built-in image_gen; exact four prompts in prompts.json',
    'references': 'Sunny forest props/ground used only as read-only layout references. Both actors are newly generated.',
    'processing': 'Byte-for-byte PNG copies; AtlasTexture regions/margins and Sprite2D scale only. Original alpha retained.',
    'files': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in ART.glob('*.png')},
    'atlas_layout': layout,
}, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
print(json.dumps(layout, ensure_ascii=False))
